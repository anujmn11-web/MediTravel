// Get all cities for a given state
export function getCitiesForState(state) {
  return INDIA_LOCATIONS.filter((l) => l.state === state).map((l) => l.city);
}

// Get location metadata for a given state+city pair
export function getLocationMeta(state, city) {
  return INDIA_LOCATIONS.find((l) => l.state === state && l.city === city) || null;
}

